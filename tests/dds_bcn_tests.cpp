void golden_vectors() {
    for (const auto& g : k_golden) {
        std::array<std::uint8_t, 64U> out{};
        bcn::decode_block(g.bc7 ? bcn::Format::bc7 : bcn::Format::bc6h_uf16,
                          reinterpret_cast<const std::byte*>(g.block.data()), out.data());
        for (std::size_t i = 0U; i < 64U; ++i) {
            if (g.bc7) {
                assert(out[i] == g.rgba[i]);
            } else if (i % 4U != 3U) {
                assert(std::abs(int{out[i]} - int{g.rgba[i]}) <= 1);
            }
        }
    }
}

// BC6H Table.F layout: every mode places exactly the endpoint bits its
// precision needs, each (component, bit) once.
void bc6h_layout_shape() {
    // Re-derived from the mode table: {endpoint, dr, dg, db, regions}.
    struct M { int ep, dr, dg, db, regions, bits; };
    const M modes[14] = {
        {10, 5, 5, 5, 2, 75}, {7, 6, 6, 6, 2, 75}, {11, 5, 4, 4, 2, 72}, {11, 4, 5, 4, 2, 72},
        {11, 4, 4, 5, 2, 72}, {9, 5, 5, 5, 2, 72}, {8, 6, 5, 5, 2, 72}, {8, 5, 6, 5, 2, 72},
        {8, 5, 5, 6, 2, 72}, {6, 6, 6, 6, 2, 72}, {10, 10, 10, 10, 1, 60}, {11, 9, 9, 9, 1, 60},
        {12, 8, 8, 8, 1, 60}, {16, 4, 4, 4, 1, 60},
    };
    for (const auto& m : modes) {
        const int components = m.regions == 2 ? 12 : 6;
        int expected = 3 * m.ep;
        for (int c = 3; c < components; ++c) expected += (c % 3 == 0 ? m.dr : c % 3 == 1 ? m.dg : m.db);
        assert(expected == m.bits);
    }
}

void bc4_snorm_ramp() {
    // r0 = 127, r1 = -127, indices: pixel 0 -> 0, pixel 1 -> 1, pixel 2 -> 2.
    std::array<std::uint8_t, 8U> block{0x7F, 0x81, 0, 0, 0, 0, 0, 0};
    const std::uint64_t idx = (1ULL << 3U) | (2ULL << 6U);
    for (std::size_t i = 0U; i < 6U; ++i) block[2U + i] = static_cast<std::uint8_t>(idx >> (8U * i));
    std::array<std::uint8_t, 64U> out{};
    bcn::decode_block(bcn::Format::bc4_snorm, reinterpret_cast<const std::byte*>(block.data()), out.data());
    assert(out[0] == 255U && out[4] == 0U);
    assert(out[8] == 219U);  // (6*127 - 127) / 7 = 90.71 -> (90.71 + 127) * 255 / 254
    assert(out[1] == out[0] && out[3] == 255U);
    // -128 is clamped to -127.
    block[1] = 0x80;
    bcn::decode_block(bcn::Format::bc4_snorm, reinterpret_cast<const std::byte*>(block.data()), out.data());
    assert(out[4] == 0U);
}

void dxt_parity_with_dds_bc() {
    std::mt19937 rng(7U);
    for (const auto code : {fourcc("DXT1"), fourcc("DXT5")}) {
        const std::size_t payload = code == fourcc("DXT1") ? 32U * 32U / 2U : 32U * 32U;
        auto dds = make_dds(32U, 32U, 1U, code, 0U, payload);
        for (std::size_t i = 128U; i < dds.size(); ++i) dds[i] = static_cast<std::byte>(rng() & 0xFFU);
        const auto a = bc::parse(view(dds));
        const auto b = bcn::parse(view(dds));
        assert(a.ok() && b.ok());
        const auto da = bc::decode_base_mip_rgba8(view(dds), a.document);
        const auto db = bcn::decode_preview_rgba8(view(dds), b.document);
        assert(da.ok && db.ok && da.image.rgba8 == db.image.rgba8);
    }
}

void header_variants() {
    // Legacy FourCC set.
    struct F { std::uint32_t code; bcn::Format format; bool pre; };
    const F legacy[] = {
        {fourcc("DXT1"), bcn::Format::bc1, false}, {fourcc("DXT2"), bcn::Format::bc2, true},
        {fourcc("DXT3"), bcn::Format::bc2, false}, {fourcc("DXT4"), bcn::Format::bc3, true},
        {fourcc("DXT5"), bcn::Format::bc3, false}, {fourcc("ATI1"), bcn::Format::bc4_unorm, false},
        {fourcc("BC4U"), bcn::Format::bc4_unorm, false}, {fourcc("BC4S"), bcn::Format::bc4_snorm, false},
        {fourcc("ATI2"), bcn::Format::bc5_unorm, false}, {fourcc("BC5U"), bcn::Format::bc5_unorm, false},
        {fourcc("BC5S"), bcn::Format::bc5_snorm, false},
    };
    for (const auto& f : legacy) {
        const auto dds = make_dds(8U, 8U, 1U, f.code, 0U, 4U * bcn::block_bytes(f.format));
        const auto p = bcn::parse(view(dds));
        assert(p.ok() && p.document.format == f.format && p.document.premultiplied == f.pre);
        assert(!p.document.dx10_header && p.document.header_size == 128U);
    }
    // DX10 DXGI set.
    struct D { std::uint32_t dxgi; bcn::Format format; bool srgb; };
    const D dx10[] = {
        {71U, bcn::Format::bc1, false}, {72U, bcn::Format::bc1, true}, {74U, bcn::Format::bc2, false},
        {77U, bcn::Format::bc3, false}, {80U, bcn::Format::bc4_unorm, false},
        {81U, bcn::Format::bc4_snorm, false}, {83U, bcn::Format::bc5_unorm, false},
        {84U, bcn::Format::bc5_snorm, false}, {95U, bcn::Format::bc6h_uf16, false},
        {96U, bcn::Format::bc6h_sf16, false}, {98U, bcn::Format::bc7, false},
        {99U, bcn::Format::bc7, true},
    };
    for (const auto& f : dx10) {
        const auto dds = make_dds(8U, 8U, 1U, 0U, f.dxgi, 4U * bcn::block_bytes(f.format));
        const auto p = bcn::parse(view(dds));
        assert(p.ok() && p.document.format == f.format && p.document.srgb == f.srgb);
        assert(p.document.dx10_header && p.document.header_size == 148U);
        assert(p.document.total_size == dds.size());
    }
    // Rejections: RGBA8 (not a block format), cube, array, truncated chain.
    assert(bcn::parse(view(make_dds(8U, 8U, 1U, 0U, 28U, 256U))).status ==
           bcn::Status::unsupported_format);
    auto cube = make_dds(8U, 8U, 1U, 0U, 98U, 64U);
    put_u32(cube, 136U, 4U);
    assert(bcn::parse(view(cube)).status == bcn::Status::invalid_header);
    auto array = make_dds(8U, 8U, 1U, 0U, 98U, 64U);
    put_u32(array, 140U, 2U);
    assert(bcn::parse(view(array)).status == bcn::Status::invalid_header);
    auto truncated = make_dds(8U, 8U, 1U, 0U, 98U, 64U);
    truncated.pop_back();
    assert(bcn::parse(view(truncated)).status == bcn::Status::payload_out_of_bounds);
}

void preview_selection() {
    // 64x64 BC7 with a full chain: a 1024-pixel budget picks mip 1 (32x32).
    std::uint64_t chain = 0U;
    assert(bcn::chain_size(64U, 64U, 7U, bcn::Format::bc7, &chain));
    assert(chain == 4096U + 1024U + 256U + 64U + 16U + 16U + 16U);
    auto dds = make_dds(64U, 64U, 7U, 0U, 98U, chain);
    // Mode 6 blocks with every endpoint at 0x7F: a flat grey, opaque image.
    for (std::size_t i = 148U; i < dds.size(); i += 16U) {
        dds[i] = std::byte{0x40};
        for (std::size_t k = 1U; k < 16U; ++k) dds[i + k] = std::byte{0};
    }
    const auto p = bcn::parse(view(dds));
    assert(p.ok() && p.document.mip_count == 7U);
    const auto mip = bcn::decode_preview_rgba8(view(dds), p.document, 32U * 32U);
    assert(mip.ok && mip.mip_level == 1U && mip.downscale == 1U && mip.image.width == 32U);

    // Single level 64x64: the same budget box-filters by 2.
    auto single = make_dds(64U, 64U, 1U, 0U, 98U, 4096U);
    for (std::size_t i = 148U; i < single.size(); i += 16U) single[i] = std::byte{0x40};
    const auto ps = bcn::parse(view(single));
    const auto boxed = bcn::decode_preview_rgba8(view(single), ps.document, 32U * 32U);
    assert(boxed.ok && boxed.downscale == 2U && boxed.image.width == 32U && boxed.image.height == 32U);
    const auto exact = bcn::decode_level_rgba8(view(single), ps.document, 0U);
    assert(exact.ok);
    // Flat blocks: filtered pixel equals the source pixel.
    for (std::size_t c = 0U; c < 4U; ++c) assert(boxed.image.rgba8[c] == exact.image.rgba8[c]);
}

void reserved_modes() {
    std::array<std::uint8_t, 16U> zero{};
    std::array<std::uint8_t, 64U> out{};
    out.fill(0xAA);
    bcn::decode_block(bcn::Format::bc7, reinterpret_cast<const std::byte*>(zero.data()), out.data());
    for (const auto v : out) assert(v == 0U);
    std::array<std::uint8_t, 16U> bc6{0x13};  // 0b10011: reserved
    bcn::decode_block(bcn::Format::bc6h_uf16, reinterpret_cast<const std::byte*>(bc6.data()), out.data());
    assert(out[0] == 0U && out[1] == 0U && out[2] == 0U && out[3] == 255U);
}

