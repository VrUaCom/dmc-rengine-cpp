void put_u32(std::vector<std::byte>& b, std::size_t o, std::uint32_t v) {
    for (std::size_t i = 0U; i < 4U; ++i) b[o + i] = static_cast<std::byte>((v >> (8U * i)) & 0xFFU);
}

constexpr std::uint32_t fourcc(const char (&s)[5]) {
    return static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[0])) |
        (static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[1])) << 8U) |
        (static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[2])) << 16U) |
        (static_cast<std::uint32_t>(static_cast<std::uint8_t>(s[3])) << 24U);
}

// DDS with the given number of mip levels; dxgi != 0 writes a DX10 header.
std::vector<std::byte> make_dds(std::uint32_t w, std::uint32_t h, std::uint32_t mips,
                                std::uint32_t code, std::uint32_t dxgi, std::size_t payload) {
    const std::size_t header = dxgi != 0U ? 148U : 128U;
    std::vector<std::byte> b(header + payload);
    put_u32(b, 0U, fourcc("DDS "));
    put_u32(b, 4U, 124U);
    put_u32(b, 8U, 0x1007U | (mips > 1U ? 0x20000U : 0U));
    put_u32(b, 12U, h);
    put_u32(b, 16U, w);
    put_u32(b, 28U, mips > 1U ? mips : 0U);
    put_u32(b, 76U, 32U);
    put_u32(b, 80U, 4U);
    put_u32(b, 84U, dxgi != 0U ? fourcc("DX10") : code);
    put_u32(b, 108U, 0x1000U);
    if (dxgi != 0U) {
        put_u32(b, 128U, dxgi);
        put_u32(b, 132U, 3U);
        put_u32(b, 140U, 1U);
    }
    return b;
}

